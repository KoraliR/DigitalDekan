export const motivationQuotes: readonly MotivationQuote[] = (Object.keys(quoteGroups) as QuoteCategory[])
  .flatMap((category) => quoteGroups[category].map((item, index) => ({
    id: category + "-" + (index + 1),
    text: item.text,
    author: item.author,
    source: item.source,
    category,
  })));

const fallback = motivationQuotes[0];

export function randomQuote(random: () => number = Math.random): MotivationQuote {
  return motivationQuotes[Math.floor(random() * motivationQuotes.length)] ?? fallback;
}

/** Следующая случайная цитата, не повторяющая текущую. */
export function nextQuote(currentId?: string, random: () => number = Math.random): MotivationQuote {
  const pool = currentId ? motivationQuotes.filter((quote) => quote.id !== currentId) : motivationQuotes;
  return pool[Math.floor(random() * pool.length)] ?? fallback;
}

export function quoteCategoryLabel(quote: MotivationQuote) {
  return quoteCategories[quote.category];
}
