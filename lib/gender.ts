// Имена, которые встречаются у обоих полов: по ним решают отчество и фамилия.
const unisexFirst = new Set(["саша", "женя", "валя", "слава"]);

export function genderFromName(name: string): StudentGender | null {
  const words = name.trim().split(/\s+/).filter(Boolean);
  if (!words.length) return null;
  for (const word of words) {
    const key = word.toLowerCase();
    if (unisexFirst.has(key)) continue;
    if (maleFirst.has(key)) return "MALE";
    if (femaleFirst.has(key)) return "FEMALE";
  }
  for (const word of words) {
    if (/(?:вич|ич)$/i.test(word)) return "MALE";
    if (/(?:вна|чна|ична)$/i.test(word)) return "FEMALE";
  }
  const last = words[words.length - 1];
  if (/(?:ова|ева|ёва|ина|ына|ая|яя)$/i.test(last) && !/(?:ий|ый)$/i.test(last)) return "FEMALE";
  if (/(?:ов|ев|ёв|ин|ын|ий|ый|ский|цкий|ко|ук|юк)$/i.test(last)) return "MALE";
  const first = words[0];
  if (/[ая]$/i.test(first)) return "FEMALE";
  if (/[йьбвгдджзклмнпрстфхцчшщ]$/i.test(first)) return "MALE";
  return null;
}
